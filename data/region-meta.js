// 시/구를 하나의 평평한 목록으로 펼친 것 (시·구 단위 페이지 생성용)
export const AREAS = [];
for (const city of CITIES) {
  const cityRegions = [];
  if (city.districts) {
    for (const d of city.districts) {
      AREAS.push({ key: d.key, cityKey: city.key, label: city.key + " " + d.key, type: "district", regions: d.regions });
      cityRegions.push(...d.regions);
    }
  }
  if (city.regions) cityRegions.push(...city.regions);
  AREAS.push({ key: city.key, cityKey: city.key, label: city.key, type: "city", regions: cityRegions });
}

export const AREA_KEYS = AREAS.map((a) => a.key);

// 동 이름 → 소속 시/구 정보 (예: REGION_TO_AREA["일동"] = { city: "안산시", district: "상록구" })
export const REGION_TO_AREA = {};
for (const city of CITIES) {
  if (city.districts) {
    for (const d of city.districts) {
      for (const r of d.regions) REGION_TO_AREA[r] = { city: city.key, district: d.key };
    }
  }
  if (city.regions) {
    for (const r of city.regions) REGION_TO_AREA[r] = { city: city.key, district: null };
  }
}
