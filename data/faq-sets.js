// 지역명/서비스명을 실제 값으로 바꿔주는 함수
export function fillFaq(text, region, serviceName) {
  return text.split("{지역}").join(region).split("{서비스}").join(serviceName);
}

// 해당 서비스의 FAQ를 지역명이 채워진 상태로 돌려줍니다.
export function getFaqs(serviceKey, region, serviceName) {
  const set = FAQ_SETS[serviceKey];
  if (!set) return [];
  return set.map((item) => ({
    q: fillFaq(item.q, region, serviceName),
    a: fillFaq(item.a, region, serviceName),
  }));
}
